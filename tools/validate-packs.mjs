// Validate the Cybertechnology packs against the captured data (docs/PLAN-cybertechnology-phase1.md):
// every inventory line covered, ids match the registry, no unresolved values, ratingStats
// sorted/unique, implant-weapon pairs resolve, source flags on every document.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { ITEMS } from "../data/items.mjs";

const errors = [];
const fail = (m) => errors.push(m);
const tsv = (p) => readFileSync(p, "utf8").trimEnd().split("\n").slice(1).map(l => l.split("\t"));
const inventory = tsv("data/inventory.tsv");
const ids = JSON.parse(readFileSync("data/ids.json", "utf8"));
const manifest = JSON.parse(readFileSync("module.json", "utf8"));

// Coverage: every inventory line resolves to a shipped item.
const covered = new Map();
for (const s of ITEMS) for (const k of [s.key, s.from, s.expand?.from, ...(s.covers ?? []),
  ...(s.rows ?? []).flatMap(r => [r.from, r.derivedFrom])].filter(Boolean)) if (!covered.has(k)) covered.set(k, s);
const rows = [];
for (const [key, page, section, entry, level] of inventory) {
  const s = covered.get(key);
  if (!s) fail(`inventory ${key} (${entry}) is not shipped`);
  rows.push(`| ${key} | p.${page} | ${section} | ${entry}${level ? ` (${level})` : ""} | ${s ? `${s.pack}: ${s.name}` : "**MISSING**"} |`);
}

// Documents.
const docs = new Map();
for (const p of manifest.packs) {
  let files = [];
  try { files = readdirSync(`packs-src/${p.name}`).filter(f => f.endsWith(".json")); } catch { fail(`pack dir missing: ${p.name}`); }
  if (p.type === "Actor") continue;
  for (const f of files) {
    const d = JSON.parse(readFileSync(`packs-src/${p.name}/${f}`, "utf8"));
    if (docs.has(d._id)) fail(`duplicate id ${d._id}`);
    docs.set(d._id, d);
    if (!/^[A-Za-z0-9]{16}$/.test(d._id)) fail(`${d.name}: bad id ${d._id}`);
    if (d.flags?.sr2e?.source?.book !== "Cybertechnology") fail(`${d.name}: no source flag`);
    const s = d.system ?? {};
    for (const k of ["capacityUsed", "capacityOver", "moduleCost", "actualEssenceCost", "actualBodyCost"]) if (k in s) fail(`${d.name}: stores derived ${k}`);
    if (typeof s.cost !== "number" || Number.isNaN(s.cost)) fail(`${d.name}: cost not a number`);
    if (d.type === "cyberware" && typeof s.essenceCost !== "number") fail(`${d.name}: essence not a number`);
    const rs = s.ratingStats ?? [];
    for (let i = 1; i < rs.length; i++) if (!(rs[i].rating > rs[i - 1].rating)) fail(`${d.name}: ratingStats not sorted/unique`);
    if (rs.length && (rs[0].cost !== s.cost || rs[0].essenceCost !== s.essenceCost)) fail(`${d.name}: authored values differ from its first rating row`);
  }
}
const byKey = new Map(Object.entries(ids));
for (const d of docs.values()) {
  const pw = d.flags?.sr2e?.pairedWeapon, pv = d.flags?.sr2e?.pairedWare;
  if (pw && !docs.has(byKey.get(pw))) fail(`${d.name}: paired weapon ${pw} missing`);
  if (pv && !docs.has(byKey.get(pv))) fail(`${d.name}: paired ware ${pv} missing`);
}
for (const s of ITEMS) if (!docs.has(ids[s.key])) fail(`${s.key}: no document with registry id`);

writeFileSync("docs/COVERAGE.md", `# Coverage — Cybertechnology (FASA 7119)

Generated by \`npm run validate\` from data/inventory.tsv and data/items.mjs. Every
source entry and the item that ships it. Rulings on printed conflicts: data/rulings.tsv.

| Capture key | Page | Section | Entry | Shipped as |
|---|---|---|---|---|
${rows.join("\n")}
`);
if (errors.length) { console.error(errors.join("\n")); console.error(`${errors.length} error(s)`); process.exit(1); }
console.log(`OK: ${inventory.length} inventory lines covered, ${docs.size} item documents.`);
